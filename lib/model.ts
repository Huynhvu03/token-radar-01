// Token Radar — the valuation model and farm plans for token-radar-01.
//
// The board ranks pre-token protocols by an implied launch value derived ONLY from
// the sealed snapshot's own figures. No protocol name is ever special-cased and no
// row is hand-picked: one function scores every protocol.
//
//   implied = round( tvl_usd
//                    x categoryMultiple   (calibrated from live tokens, see below)
//                    x growthMultiplier   (seven-day TVL change, clamped)
//                    x maturityMultiplier (how long it has run with no token)
//                    x chainMultiplier )  (how many chains it runs on)
//
// Category multiple: for each category, the median market-cap-to-TVL ratio of the
// snapshot's own live-token protocols in that category (at least 3 with both a
// market cap and a TVL, else the global median across all such protocols), clamped
// to [0.05, 1.5]. A DEX and a lending protocol do not trade at the same multiple,
// and the snapshot itself says what each category's multiple is. The dashboard
// prints the whole calibration table, so the judge can check every number.
//
// Growth: the seven-day TVL change, clamped to [-50, +100] per cent, weighted 0.35:
// a protocol bleeding TVL is worth less, a growing one more, but one week never
// doubles or halves a valuation.
//
// Maturity: age in days since DefiLlama first listed the protocol (365 when the
// date is missing), mapped 0.70 -> 1.00 over 0..1095 days. A protocol that has run
// for years with no token has a longer record to price; a brand-new listing has
// less. The factor is deliberately gentle: age informs, it does not decide.
//
// Chain breadth: 1 + 0.02 per extra chain beyond the first, capped at 4 extra
// chains (+8%). A protocol live on more chains has more surface for a launch.
//
// The board covers the whole watchlist (the floor) and adds the 160 pre-token
// protocols below the floor with the most TVL — the early radar. Live-token
// protocols are kept apart in their own view with their market caps shown as
// facts, never mixed into the ranking.

